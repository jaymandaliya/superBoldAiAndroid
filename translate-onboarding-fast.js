const main = () => {
  const labelsPath = path.join(__dirname, 'src', 'localization', 'labels.all.json');
  const allLabels = JSON.parse(fs.readFileSync(labelsPath, 'utf8'));

  let updated = 0;

  for (const [langCode, translations] of Object.entries(ONBOARDING_TRANSLATIONS)) {
    if (!allLabels[langCode]) {
      console.log(`⚠️  ${langCode} not found`);
      continue;
    }

    console.log(`📝 ${langCode}: Updating ${Object.keys(translations).length} keys`);

    for (const [key, value] of Object.entries(translations)) {
      allLabels[langCode][key] = value;
      updated++;
    }
  }

  fs.writeFileSync(labelsPath, JSON.stringify(allLabels, null, 2), 'utf8');
  console.log(`\n✅ Updated ${updated} translations!`);
};

main();
